"""
Script to aggregate and evaluate the final ensemble predictions.
It loads the JSON prediction files generated by each of the 5 cross-validation folds,
averages their probabilities to form an ensemble prediction for each patient,
and computes key clinical metrics including AUROC (Malignant vs Rest), 
Sensitivity, and Specificity. It also generates and saves a confusion matrix plot.
"""

import json
import os
import sys
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.metrics import roc_auc_score, confusion_matrix, roc_curve

# Config
if len(sys.argv) > 1:
    output_dir = sys.argv[1]
else:
    output_dir = "Training_results"
metadata_path = "Log_and_helper_files/odelia_merged_metadata.csv"
fold_files = [os.path.join(output_dir, f"predictions_fold{i}.json") for i in range(5)]
final_json_output = os.path.join(output_dir, "final_ensemble_predictions.json")

# Load Labels
df = pd.read_csv(metadata_path)
df['Lesion'] = df['Lesion'].astype(int) 
uid_to_label = dict(zip(df['UID'], df['Lesion']))

# Accumulate probabilities by fold
temp_probs = {}
for file in fold_files:
    if os.path.exists(file):
        with open(file, 'r') as f:
            data = json.load(f)
            for uid, res in data.items():
                if uid not in temp_probs: temp_probs[uid] = []
                temp_probs[uid].append(res['probabilities'])

# Computing the means
ensemble_json_data = {}
y_true, y_scores = [], []

for uid, list_of_probs in temp_probs.items():
    if uid in uid_to_label:
        cleaned_probs = []
        for p in list_of_probs:
            p_np = np.array(p).squeeze()
            if p_np.shape == (3,):
                cleaned_probs.append(p_np)
        
        if not cleaned_probs:
            continue

        # Mean on the folds
        mean_p = np.mean(cleaned_probs, axis=0)
        
        y_true.append(uid_to_label[uid])
        y_scores.append(mean_p)
        
        ensemble_json_data[uid] = {
            "prediction": int(np.argmax(mean_p)),
            "mean_probabilities": mean_p.tolist(),
            "true_label": int(uid_to_label[uid])
        }

if len(y_scores) == 0:
    print("❌ Error : No scores could be retrieved. Please check the UIDs or the probability format.")
    sys.exit(1)

y_true = np.array(y_true)
y_scores = np.vstack(y_scores)
y_pred = np.argmax(y_scores, axis=1)

# Computing Clinical metrics (Malignant vs Rest) 
y_true_binary = (y_true == 2).astype(int)
y_scores_malignant = y_scores[:, 2]

print(f"\n" + "="*40)
print(f"🏆 ENSEMBLE RESULTS ({len(y_true)} patients)")
print("="*40)

if len(np.unique(y_true_binary)) > 1:
    fpr, tpr, thresholds = roc_curve(y_true_binary, y_scores_malignant)
    
    # Sensitivity @ 90% Specificity (FPR = 0.10)
    idx_90_spec = np.argmin(np.abs(fpr - 0.10))
    sens_at_90_spec = tpr[idx_90_spec]

    # Specificity @ 90% Sensitivity (TPR = 0.90)
    idx_90_sens = np.argmin(np.abs(tpr - 0.90))
    spec_at_90_sens = 1 - fpr[idx_90_sens]

    print(f"✅ AUROC Malignant vs Rest      : {roc_auc_score(y_true_binary, y_scores_malignant):.4f}")
    print(f"✅ Sensitivity @ 90% Specif. : {sens_at_90_spec*100:.2f}%")
    print(f"✅ Specificity @ 90% Sensit. : {spec_at_90_sens*100:.2f}%")
print("="*40 + "\n")

# Confusion Matrix
cm = confusion_matrix(y_true, y_pred)
classes = ['Normal', 'Benign', 'Malignant']

fig, ax = plt.subplots(figsize=(8, 6))
im = ax.imshow(cm, interpolation='nearest', cmap=plt.cm.Blues)
ax.figure.colorbar(im, ax=ax)

ax.set(xticks=np.arange(cm.shape[1]),
       yticks=np.arange(cm.shape[0]),
       xticklabels=classes, yticklabels=classes,
       title='Final Confusion Matrix (Ensemble)',
       ylabel='True Label',
       xlabel='Model Prediction')

thresh = cm.max() / 2.
for i in range(cm.shape[0]):
    for j in range(cm.shape[1]):
        ax.text(j, i, format(cm[i, j], 'd'),
                ha="center", va="center",
                color="white" if cm[i, j] > thresh else "black")

plt.tight_layout()
plt.savefig(os.path.join(output_dir, "confusion_matrix_ensemble.png"))
print(f"✅ Image of the generated matrix : {output_dir}/confusion_matrix_ensemble.png")
